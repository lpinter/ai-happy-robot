"""Adds an "ESP32S3 N16R8 (Happy Robot)" board to the Arduino IDE.

It is a copy of "ESP32S3 Dev Module" whose menus start on the settings this
robot needs, so you never have to set them by hand:
  PSRAM: OPI PSRAM, Flash Size: 16MB, Partition Scheme: 16M Flash (3MB APP/9.9MB FATFS)

The board goes into boards.local.txt of the newest installed esp32 core.
Run it again after every esp32 core update (the update makes a new folder).

Usage:  python tools/make_happy_board.py
Then restart the Arduino IDE and pick Tools > Board > esp32 > ESP32S3 N16R8 (Happy Robot).
"""
import os
import re
import sys
from pathlib import Path

SRC_ID = "esp32s3"
NEW_ID = "happys3"
NEW_NAME = "ESP32S3 N16R8 (Happy Robot)"
# menu -> option that should come first (= the default)
DEFAULTS = {
    "PSRAM": "opi",
    "FlashSize": "16M",
    "PartitionScheme": "app3M_fat9M_16MB",
}
BEGIN = f"# ---- BEGIN {NEW_ID} (generated by make_happy_board.py, do not edit) ----"
END = f"# ---- END {NEW_ID} ----"


def find_core() -> Path:
    if sys.platform == "win32":
        base = Path(os.environ["LOCALAPPDATA"]) / "Arduino15"
    elif sys.platform == "darwin":
        base = Path.home() / "Library" / "Arduino15"
    else:
        base = Path.home() / ".arduino15"
    root = base / "packages" / "esp32" / "hardware" / "esp32"
    versions = [d for d in root.glob("*") if (d / "boards.txt").is_file()]
    if not versions:
        sys.exit(f"No esp32 core found in {root}. Install it in Boards Manager first.")

    def key(d: Path):
        return [int(n) if n.isdigit() else n for n in re.split(r"[.\-]", d.name)]

    return max(versions, key=key)


def build_board(boards_txt: Path) -> list[str]:
    lines = [l.rstrip("\n") for l in boards_txt.read_text(encoding="utf-8").splitlines()]
    src = [l for l in lines if l.startswith(SRC_ID + ".")]
    if not src:
        sys.exit(f"Board '{SRC_ID}' not found in {boards_txt}.")
    out = [NEW_ID + l[len(SRC_ID):] for l in src]
    out = [f"{NEW_ID}.name={NEW_NAME}" if l.startswith(f"{NEW_ID}.name=") else l for l in out]

    # The IDE uses the first option of each menu as the default, so move the
    # wanted option's lines in front of that menu's first line.
    for menu, opt in DEFAULTS.items():
        menu_prefix = f"{NEW_ID}.menu.{menu}."
        opt_prefix = f"{menu_prefix}{opt}"
        moved = [l for l in out if l.startswith(opt_prefix + "=") or l.startswith(opt_prefix + ".")]
        if not moved:
            sys.exit(f"Option {menu}={opt} not found in {boards_txt}; the core changed, update DEFAULTS.")
        rest = [l for l in out if l not in moved]
        first = next(i for i, l in enumerate(rest) if l.startswith(menu_prefix))
        out = rest[:first] + moved + rest[first:]
    return out


def main():
    core = find_core()
    board = build_board(core / "boards.txt")
    local = core / "boards.local.txt"

    # Keep anything else that is already in boards.local.txt; replace only our block.
    old = local.read_text(encoding="utf-8") if local.exists() else ""
    old = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", "", old, flags=re.S).rstrip()
    text = (old + "\n\n" if old else "") + "\n".join([BEGIN, *board, END]) + "\n"
    local.write_text(text, encoding="utf-8")

    print(f"Wrote {len(board)} lines for '{NEW_NAME}' to:\n  {local}")
    print("Defaults: " + ", ".join(f"{m}={o}" for m, o in DEFAULTS.items()))
    print("Restart the Arduino IDE, then pick Tools > Board > esp32 > " + NEW_NAME)


if __name__ == "__main__":
    main()
